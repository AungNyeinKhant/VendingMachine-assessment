        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {YOUR_JWT_TOKEN}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Get a JWT token by calling <code>POST /api/v1/auth/login</code> with email and password. Use the <code>access_token</code> as Bearer token.</p>

        <h1 id="authentication">Authentication</h1>

    <p>Get a JWT access token and inspect the current user.</p>

                                <h2 id="authentication-POSTapi-v1-auth-login">Log in</h2>

<p>
</p>

<p>Exchange email and password for a JWT (HS256, 60 minutes). Send it as
<code>Authorization: Bearer &lt;token&gt;</code> on protected endpoints. Rate-limited to 5 attempts per minute.</p>

<span id="example-requests-POSTapi-v1-auth-login">
<blockquote>Example request:</blockquote>


<div class="bash-example">
    <pre><code class="language-bash">curl --request POST \
    "http://localhost:8000/api/v1/auth/login" \
    --header "Content-Type: application/json" \
    --header "Accept: application/json" \
    --data "{
    \"email\": \"user@vending.test\",
    \"password\": \"password\"
}"
</code></pre></div>


<div class="javascript-example">
    <pre><code class="language-javascript">const url = new URL(
    "http://localhost:8000/api/v1/auth/login"
);

const headers = {
